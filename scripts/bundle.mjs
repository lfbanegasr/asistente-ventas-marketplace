import { readFileSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const types = { 'index.html': 'text/html; charset=utf-8', 'login.html': 'text/html; charset=utf-8', 'style.css': 'text/css; charset=utf-8', 'app.js': 'text/javascript; charset=utf-8', 'login.js': 'text/javascript; charset=utf-8', 'manifest.webmanifest': 'application/manifest+json; charset=utf-8' };
const assets = Object.fromEntries(Object.entries(types).map(([name, type]) => [`/${name}`, { type, body: readFileSync(join(root, 'public', name), 'utf8') }]));
writeFileSync(join(root, 'src', 'bundled-assets.js'), `// Generated by npm run build. Do not edit.\nexport const bundledAssets = ${JSON.stringify(assets)};\n`);
const schema = readFileSync(join(root, 'migrations', '0001_init.sql'), 'utf8')
  .replace(/^--.*$/gm, '')
  .replace(/\s+/g, ' ')
  .replace(/;\s*/g, ';\n')
  .trim();
writeFileSync(join(root, 'src', 'bundled-schema.js'), `// Generated by npm run build. Do not edit.\nexport const initialSchema = ${JSON.stringify(schema)};\n`);
